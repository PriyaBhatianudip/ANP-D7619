# input two numbers
a = int(input("Enter first number: "))
b = int(input("Enter second number : "))

# perform arithmetic operations
print("Sum : ", a+b)
print("Difference : ", a-b)
print("Product : ", a*b)
print("Division :",a/b)
print("Floor Division : ", a//b)
print("Exponent : ", a**3)
print("Modulus : ", a%b)

# comparison of two values
print(f"a == b : {a==b}")
print(f"a != b : {a!=b}")
print(f"a > b : {a>b}")
print(f"a < b : {a<b}")
print(f"a >= b : {a>=b}")
print(f"a <= b : {a<=b}")
